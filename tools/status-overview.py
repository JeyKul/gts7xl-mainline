#!/usr/bin/env python3
"""Regenerate the "At a glance" block in README.md from the status tables.

Reads every table row whose second column is a state emoji
(✅ working, 🟡 partial, ❌ not working, ⬜ not started), and rewrites the
text between the overview markers. Drawbacks come from docs/drawbacks.txt.
Run: python3 tools/status-overview.py   (CI runs it on every push to main)
"""
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
README = ROOT / "README.md"
DRAWBACKS = ROOT / "docs" / "drawbacks.txt"
START, END = "<!-- overview:start -->", "<!-- overview:end -->"

SQUARE = {"✅": "🟩", "🟡": "🟨", "❌": "🟥", "⬜": "⬜"}
WEIGHT = {"✅": 1.0, "🟡": 0.5, "❌": 0.0, "⬜": 0.0}

# (minimum score, label), checked from the top
TIERS = [
    (85, "Daily-driver ready"),
    (65, "Very usable, with a few drawbacks"),
    (45, "Usable for testing"),
    (25, "Boots, early bring-up"),
    (0, "Early bring-up"),
]


def parse(text):
    sections, current = [], None
    for line in text.splitlines():
        m = re.match(r"^### (.+)", line)
        if m:
            current = (m.group(1).strip(), [])
            sections.append(current)
            continue
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if current and len(cells) >= 2 and cells[1] in SQUARE:
            current[1].append((cells[0], cells[1]))
    return [s for s in sections if s[1]]


def render(sections):
    states = [st for _, rows in sections for _, st in rows]
    score = round(100 * sum(WEIGHT[s] for s in states) / len(states))
    tier = next(label for limit, label in TIERS if score >= limit)
    filled = round(score / 5)
    bar = "█" * filled + "░" * (20 - filled)
    counts = {k: states.count(k) for k in SQUARE}

    out = [
        "## At a glance",
        "",
        f"**Usability: {tier}** · `{bar}` {score}%",
        "",
    ]
    if DRAWBACKS.exists():
        notes = DRAWBACKS.read_text(encoding="utf-8").strip()
        if notes:
            out += [f"> {notes}", ""]
    out += [
        f"🟩 working {counts['✅']} · 🟨 partial {counts['🟡']} · "
        f"🟥 not working {counts['❌']} · ⬜ not started {counts['⬜']}",
        "",
        "| Area | Progress | Done |",
        "|---|---|---|",
    ]
    for name, rows in sections:
        squares = "".join(SQUARE[st] for _, st in rows)
        done = sum(1 for _, st in rows if st == "✅")
        out.append(f"| {name} | {squares} | {done}/{len(rows)} |")
    out += ["", "Score: working = 1, partial = ½. Generated by `tools/status-overview.py` from the tables below."]
    return "\n".join(out)


def main():
    text = README.read_text(encoding="utf-8")
    block = f"{START}\n{render(parse(text))}\n{END}"
    if START in text:
        new = re.sub(re.escape(START) + r".*?" + re.escape(END), lambda _: block, text, flags=re.S)
    else:
        new = text.replace("## Status", block + "\n\n## Status", 1)
    if new != text:
        README.write_text(new, encoding="utf-8")
        print("README overview updated")
    else:
        print("README overview unchanged")


if __name__ == "__main__":
    main()
